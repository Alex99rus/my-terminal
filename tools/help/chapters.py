"""Сценарии глав видеоинструкции.

В каждой главе `s.say(субтитр, текст_для_голоса)` запускает озвучку, а следующие за ней действия мыши
и клавиатуры выполняются, пока голос говорит. Следующая фраза начинается, когда закончилась предыдущая.
Текст для голоса пишем словами, как читать: латиницу и сокращения — русскими буквами (Энтер, Шифт, эр-эс-ай).
"""

CHART = (480, 300)  # середина графика в окне 1280×720


def overview(s):
    s.say('Терминал: живые графики криптовалют',
          'Это ваш терминал для торговли. Здесь живые графики криптовалют, почти как в Трейдинг Вью.')
    s.mv(*CHART, dur=1.2)
    s.wait_speech(0.3)

    s.say('Сверху — главная панель',
          'Сверху находится главная панель. Здесь поле для монеты, выбор биржи, индикаторы, раскладка окон, оповещения и демо-счёт.')
    for sel in ['#symbol', '#market', '#indBtn', '#layoutBtn', '#alertsBtn', '#paperBtn']:
        s.to(sel, dur=0.7)
        s.hold(0.45)
    s.wait_speech(0.3)

    s.say('Слева — инструменты рисования',
          'Слева инструменты рисования: линии, прямоугольник, стрелки лонг и шорт, линейка и текст.')
    for i in range(1, 13):
        s.to('#toolbar button', nth=i, dur=0.35)
        s.hold(0.25)
    s.wait_speech(0.3)

    s.say('В центре — график',
          'В центре находится график. Колёсико мыши меняет масштаб. Если зажать левую кнопку и потянуть, график прокручивается.')
    s.mv(*CHART, dur=0.8)
    s.wheel(-300, 3)
    s.hold(0.4)
    s.wheel(300, 3)
    s.hold(0.4)
    s.drag((600, 320), (300, 320), dur=1.2)
    s.hold(0.4)
    s.drag((300, 320), (600, 320), dur=1.2)
    s.wait_speech(0.3)

    s.say('Справа — список монет',
          'Справа список ваших монет с живыми ценами. Щёлкните по монете, и график сразу переключится на неё.')
    s.click('.wl-row', nth=1, dur=1.0)
    s.hold(1.6)
    s.click('.wl-row', nth=0, dur=0.7)
    s.wait_speech(0.3)

    s.say('«❓ Помощь» — видео по каждой функции',
          'Если что-то непонятно, нажмите вопросительный знак наверху. Там собраны короткие видео по каждой функции.')
    s.to('#helpBtn', dur=1.0)
    s.wait_speech(0.5)



def clear_type(s, sel, text):
    """Щёлкает в поле, стирает старое и вводит новое."""
    s.click(sel, after=0.15)
    s.key('Control+a', after=0.1)
    s.type(text, after=0.25)


